@app.post("/threat-assessment")
def threat_assessment(payload: dict):
    """
    Run a detection event through the threat scoring engine.

    Body:
        {
            "sector_id": "S001",
            "confidence": 0.9,
            "event": {
                "human_detected": "...",
                "vehicle_detected": "...",
                "visibility": "...",
                "weather": "...",
                "historical_risk": 5,
                "last_patrol_hours": 2.0
            }
        }
    """
    sector_id = payload.get("sector_id")
    event = payload.get("event")
    confidence = payload.get("confidence", 1.0)

    if not sector_id or not event:
        raise HTTPException(status_code=422, detail="sector_id and event are required")

    return assess_threat(sector_id=sector_id, event=event, confidence=confidence)


