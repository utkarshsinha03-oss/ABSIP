# ─────────────────────────────────────────────
# DATA LOADING HELPERS
# ─────────────────────────────────────────────

def _load(filename: str) -> list:
    path = DATA_DIR / filename
    if not path.exists():
        raise HTTPException(status_code=500, detail=f"Data file missing: {filename}")
    with open(path, "r") as f:
        return json.load(f)


def _find_by_id(records: list, id_field: str, id_value: str) -> Optional[dict]:
    return next((r for r in records if str(r.get(id_field)) == str(id_value)), None)


