# ─────────────────────────────────────────────
# DASHBOARD SUMMARY (aggregate stats for Dashboard page)
# ─────────────────────────────────────────────

@app.get("/dashboard/summary")
def dashboard_summary():
    sectors = _load("sectors.json")
    alerts = _load("alerts.json")
    incidents = _load("incidents.json")
    patrols = _load("patrols.json")

    open_alerts = [a for a in alerts if a.get("alert_status") == "open"]
    level_counts = {}
    for a in alerts:
        level_counts[a.get("threat_level", "Unknown")] = level_counts.get(a.get("threat_level", "Unknown"), 0) + 1

    return {
        "total_sectors": len(sectors),
        "active_threat_sectors": len([s for s in sectors if s.get("active_threat_designation")]),
        "total_alerts": len(alerts),
        "open_alerts": len(open_alerts),
        "threat_level_breakdown": level_counts,
        "total_incidents": len(incidents),
        "active_patrols": len([p for p in patrols if p.get("status") == "Active"]),
        "total_patrols": len(patrols),
    }


